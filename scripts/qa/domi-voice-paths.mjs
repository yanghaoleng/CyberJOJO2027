import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright-core');
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']});
const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
const errors=[],requests=[];let channel,failSpeech=false;
const audio=(await readFile('public/audio/commands/praise.mp3')).toString('base64');
page.on('pageerror',error=>errors.push(error.message));
await page.addInitScript(()=>{
 window.voicePlaySamples=[];window.systemVoiceCalls=0;window.pcmStarts=0;
 const play=HTMLMediaElement.prototype.play;
 HTMLMediaElement.prototype.play=function(...args){voicePlaySamples.push({character:this.dataset.character,rate:this.playbackRate,pitch:this.preservesPitch,text:this.dataset.speechText||'',src:this.src});return play.apply(this,args)};
 speechSynthesis.speak=()=>{systemVoiceCalls++};
 const create=AudioContext.prototype.createBufferSource;
 AudioContext.prototype.createBufferSource=function(...args){const source=create.apply(this,args),start=source.start.bind(source);source.start=(...a)=>{pcmStarts++;return start(...a)};return source};
});
await page.route(/\/(?:api\/)?speech$/,async route=>{
 const body=route.request().postDataJSON();requests.push(body);
 await route.fulfill({status:failSpeech?502:200,contentType:'application/json',body:JSON.stringify(failSpeech?{ok:false}:{ok:true,character:'lvdou',voiceSource:'domi-word-tts-v1',text:body.text,audio,mime:'audio/mpeg'})});
});
await page.routeWebSocket('**/voice',ws=>{channel=ws;ws.onMessage(data=>{if(typeof data!=='string')return;const message=JSON.parse(data);if(message.type==='start')ws.send(JSON.stringify({type:'ready',transport:'seeduplex'}));if(message.type==='ping')ws.send(JSON.stringify({type:'pong',id:message.id}));});});
try{
 await page.goto(process.env.QA_URL||'http://127.0.0.1:4173/words');
 await page.getByRole('button',{name:'开始和叫叫聊聊',exact:true}).click();
 await page.waitForSelector('.word-bubble-play',{timeout:120000});
 await page.waitForFunction(()=>document.querySelector('.camera-stage').dataset.character==='lvdou');
 await page.getByRole('button',{name:'结束单词泡泡'}).click();
 channel.send(JSON.stringify({type:'speech',character:'lvdou',text:'Hi, I am Domi.',audio,voiceSource:'domi-word-tts-v1'}));
 await page.waitForFunction(()=>document.querySelector('audio.guide-audio').dataset.speechText==='Hi, I am Domi.');
 assert.equal(await page.locator('audio.guide-audio').evaluate(a=>a.playbackRate),1.5);
 await page.waitForTimeout(1800);
 channel.send(JSON.stringify({type:'speech',local:true,character:'jiaojiao',text:'迟到的旧角色声音',audio}));
 await page.waitForTimeout(250);
 assert.notEqual(await page.locator('audio.guide-audio').evaluate(a=>a.dataset.speechText),'迟到的旧角色声音');
 const beforePcm=await page.evaluate(()=>pcmStarts);
 channel.send(JSON.stringify({type:'speech_start',character:'lvdou',streamId:'forbidden-pcm',sampleRate:24000}));
 channel.send(JSON.stringify({type:'speech_chunk',streamId:'forbidden-pcm',audio:'AAAAAA=='}));
 await page.waitForTimeout(250);assert.equal(await page.evaluate(()=>pcmStarts),beforePcm);
 channel.send(JSON.stringify({type:'speech',character:'lvdou',local:true,text:'Apple.',audio:'legacy audio from another voice'}));
 await page.waitForFunction(()=>document.querySelector('audio.guide-audio').dataset.speechText==='Apple.');
 assert.ok(requests.some(request=>request.text==='Apple.'));
 await page.getByRole('button',{name:/打开作品列表/}).click();
 await page.getByRole('button',{name:'模拟数据',exact:true}).click();
 const domiNote=page.locator('.leave-note-card').filter({hasText:'Domi 录音'}).first();
 await domiNote.getByRole('button',{name:'播放留言'}).click();
 await page.waitForTimeout(500);
 assert.ok(requests.some(request=>request.text!== 'Apple.'),'legacy DOMI note regenerates word voice');
 await page.waitForTimeout(1600);
 failSpeech=true;
 await domiNote.getByRole('button',{name:'播放留言'}).click();
 await domiNote.getByRole('status').waitFor();
 assert.equal(await page.evaluate(()=>systemVoiceCalls),0,'failed DOMI note cannot switch to system voice');
 failSpeech=false;
 await page.getByRole('button',{name:'收集',exact:true}).click();
 await page.locator('.friend-open-card').filter({hasText:'Domi · Word card'}).first().click();
 await page.locator('.friend-detail-sheet').getByRole('button',{name:'读单词'}).click();
 await page.waitForTimeout(500);
 assert.ok(requests.length>=4);assert.ok(requests.every(request=>request.character==='lvdou'));
 const samples=await page.evaluate(()=>voicePlaySamples.filter(sample=>sample.character==='lvdou'&&sample.src.startsWith('blob:')));
 assert.ok(samples.length>=4);assert.ok(samples.every(sample=>sample.rate===1.5&&sample.pitch===true));
 assert.equal(await page.evaluate(()=>systemVoiceCalls),0);assert.deepEqual(errors,[]);
 console.log('PASS: conversation, legacy audio, DOMI notes, old notes, failed-note retry, word cards all use canonical boy TTS at 1.5x; no system voice, wrong persona, or model PCM');
}catch(error){await page.screenshot({path:'/tmp/domi-voice-paths-failure.png'});console.log('requests',requests,'errors',errors);throw error}finally{await browser.close()}
