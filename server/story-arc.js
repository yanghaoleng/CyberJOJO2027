export function getStoryArc(day, ageGroup) {
  const group = AGE_GROUPS.includes(ageGroup) ? ageGroup : "mid";
  const dayNum = Number(day);
  const safe = Number.isFinite(dayNum) ? dayNum : 1;
  const index = ((safe - 1) % STORY_ARC_DAYS + STORY_ARC_DAYS) % STORY_ARC_DAYS;
  return STORY_ARCS[group][index];
}

/**
 * 生成当天剧情指令，拼接进角色系统提示词。
 * closing=true 时强调"今天收尾 + 埋明天钩子"。
 */
export function buildStoryInstructions(day, ageGroup, { closing = false } = {}) {
  const arc = getStoryArc(day, ageGroup);
  const parts = [
    `【剧情主线·第${arc.day}天】今天你们在故事《${arc.title}》里：${arc.premise}`,
    `开场钩子：${arc.opening}`,
    `引导：${arc.guide}`,
  ];
  if (closing) {
    parts.push(`收尾：今天的故事已经讲了约三分钟，现在自然地把今天这一节收住，用这个钩子引出明天：${arc.hook}`);
  } else {
    parts.push(`今天不必急着讲完，跟随孩子节奏；等聊到大约三分钟或孩子兴致开始回落时，再收尾并抛出明天的钩子：${arc.hook}`);
  }
  parts.push("剧情要自然地融进聊天，不要像念稿子；孩子带偏话题就跟上，再轻轻带回剧情。");
  return parts.join("\n");
}
